#!/usr/bin/env python3
"""The library's axioms, as a ledger under version control.

An axiom is an unproved claim, and it has a spelling of its own: an entry of a
trait at one type whose value is true.  Two forms are read from the text of
the sources, with comments removed:

    template <> constexpr bool f<...> = true;
    template <> struct f<...> : std::true_type {};

A trait's default, an entry at a form (template <typename ...>), an entry
declared false and an entry whose value is computed are not axioms and are not
listed.  The linter's rule `axioms` reads the first form from the syntax tree
(tools/jlt-lint/rules/axioms.query); this script reads both from the text, so
that it needs no build and anyone can run it.

The ledger, tools/jlt-lint/axioms.txt, is checked in.  A change that adds,
removes or alters an axiom must change the ledger with it, so the change shows
in the diff, where a reviewer reads it: is the claim true, is it needed or
does it follow from the others, is it there twice.  Lines carry the file and
the declaration, and no line number, so that unrelated edits do not move them.

Usage: axioms.py            print the ledger
       axioms.py --write    rewrite tools/jlt-lint/axioms.txt
       axioms.py --check    fail, with the difference, if the ledger is stale
       axioms.py --selftest check the reader against fixtures/axioms.cpp
"""

import difflib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
LEDGER = ROOT / "tools" / "jlt-lint" / "axioms.txt"
LAWS = ROOT / "tools" / "jlt-lint" / "laws.txt"
SOURCES = "src/main/modules/dedekind"

COMMENT = re.compile(r"//[^\n]*|/\*.*?\*/", re.S)
ENTRY = re.compile(
    r"template\s*<\s*>\s*(?:inline\s+)?constexpr\s+bool\s+"
    r"(?P<what>[A-Za-z_]\w*\s*<[^;=]*>)\s*=\s*(?:\(\s*)*true(?:\s*\))*\s*;"
)
STRUCT = re.compile(
    r"template\s*<\s*>\s*struct\s+"
    r"(?P<what>[A-Za-z_]\w*\s*<[^;{]*>)\s*:\s*(?:public\s+)?std::true_type\s*\{\s*\}\s*;"
)


# Every entry of a law: a template head (empty for one type), a clause, the
# law at its arguments, and its value.  The conditional laws are those that
# are not axioms and not declared false.
LAW = re.compile(
    r"template\s*<(?P<params>[^;{}]*?)>\s*"
    r"(?:requires\s+(?P<req>[^;{}]*?)\s+)?(?:inline\s+)?constexpr\s+bool\s+"
    r"(?P<what>[A-Za-z_]\w*\s*<[^;=]*>)\s*=\s*(?P<value>[^;]*);"
)
LAW_STRUCT = re.compile(
    r"template\s*<(?P<params>[^;{}]*?)>\s*(?:requires\s+(?P<req>[^;{}]*?)\s+)?struct\s+"
    r"(?P<what>[A-Za-z_]\w*\s*<[^;{]*>)\s*:\s*(?:public\s+)?"
    r"(?P<value>std::true_type|std::bool_constant\s*<[^{]*>)\s*\{\s*\}\s*;"
)


# A floating type is a total magma (the user, 2026-11-23): its operations
# are total, and no law is declared of them, not even commutativity.
FLOATING = re.compile(r"\b(?:float|double)\b")


def at_floating_type(line):
    """Whether a ledger line declares a law at a floating type: its head (the
    law at its arguments, before any clause or value) names one."""
    head = line.split(" requires ", 1)[0].split(" = ", 1)[0]
    return bool(FLOATING.search(head))


def norm(t):
    return " ".join(t.split())


def laws_of(text):
    """The conditional laws a source text declares: every entry of a law that
    can make it true and is not an axiom, an entry at a form (a template head
    with parameters) or one whose value is computed; each as one normalised
    line, head, clause and value, which is what a reviewer must judge."""
    text = COMMENT.sub("", text)
    found = []
    for m in list(LAW.finditer(text)) + list(LAW_STRUCT.finditer(text)):
        params, value = norm(m.group("params")), norm(m.group("value"))
        bare = value.strip("() ")
        if bare in ("false", "std::false_type"):
            continue  # declared not known
        if not params and bare in ("true", "std::true_type"):
            continue  # an axiom: the other ledger
        line = norm(m.group("what"))
        if params:
            line = f"template <{params}> " + line
        if m.group("req"):
            line += f" requires {norm(m.group('req'))}"
        found.append(f"{line} = {value}")
    return sorted(found)


def axioms_of(text):
    """The axioms a source text declares, each as one normalised line."""
    text = COMMENT.sub("", text)
    found = [m.group("what") for m in ENTRY.finditer(text)]
    found += [m.group("what") for m in STRUCT.finditer(text)]
    return sorted(" ".join(w.split()) for w in found)


def ledger(read=None):
    read = read or axioms_of
    lines = []
    for path in sorted((ROOT / SOURCES).rglob("*.cppm")):
        rel = path.relative_to(ROOT / SOURCES)
        lines += [f"{rel}: {a}" for a in read(path.read_text(encoding="utf-8"))]
    return lines


LAWS_HEADER = [
    "# The library's conditional laws: every entry of a trait that can make it true",
    "# and is not an axiom, an entry at a form or one whose value is computed.",
    "# Generated by tools/jlt-lint/axioms.py --write, and held by --check in CI.",
    "# A reviewer reads each added line: does the law follow from the clause and",
    "# the parts, for every instance of the form? needed? there twice?",
]

HEADER = [
    "# The library's axioms: every entry of a trait at one type whose value is true.",
    "# Generated by tools/jlt-lint/axioms.py --write, and held by --check in CI.",
    "# A reviewer reads each added line: true? needed, or does it follow? there twice?",
]


def main(argv):
    if "--selftest" in argv:
        got = axioms_of((ROOT / "tools/jlt-lint/fixtures/axioms.cpp").read_text(encoding="utf-8"))
        want = ["associative<unsigned, Plus>", "injective<Neg>", "injective<Succ>", "outside<int>"]
        if got != want:
            sys.exit(f"axioms.py: selftest: read {got}, expected {want}")
        got = laws_of((ROOT / "tools/jlt-lint/fixtures/axioms.cpp").read_text(encoding="utf-8"))
        want = ["associative<int, Plus> = injective<Succ>",
                "template <typename F, typename G> injective<Then<F, G>> = injective<F> && injective<G>",
                "template <typename F> associative<F, Then<F, F>> = true"]
        if got != sorted(want):
            sys.exit(f"axioms.py: selftest: laws read {got}, expected {sorted(want)}")
        if not at_floating_type("x.cppm: associative<double, Plus>") or \
                at_floating_type("x.cppm: template <typename T> f<T> requires std::floating_point<T> = false"):
            sys.exit("axioms.py: selftest: the floating-type guard misreads")
        print("axioms.py: selftest passed")
        return
    current = HEADER + ledger()
    laws = LAWS_HEADER + ledger(laws_of)
    floating = [l for l in current + laws if not l.startswith("#") and at_floating_type(l)]
    if floating:
        sys.exit("axioms.py: a law at a floating type: a floating type is a total magma, and "
                 "no law is declared of its operations:\n  " + "\n  ".join(floating))
    if "--write" in argv:
        LEDGER.write_text("\n".join(current) + "\n", encoding="utf-8")
        LAWS.write_text("\n".join(laws) + "\n", encoding="utf-8")
        print(f"axioms.py: wrote {len(current) - len(HEADER)} axioms to {LEDGER.relative_to(ROOT)}, "
              f"{len(laws) - len(LAWS_HEADER)} conditional laws to {LAWS.relative_to(ROOT)}")
        return
    if "--check" in argv:
        held_laws = LAWS.read_text(encoding="utf-8").splitlines() if LAWS.exists() else []
        if held_laws != laws:
            sys.stdout.writelines(
                difflib.unified_diff(
                    [l + "\n" for l in held_laws],
                    [l + "\n" for l in laws],
                    "tools/jlt-lint/laws.txt (checked in)",
                    "the sources",
                )
            )
            sys.exit(
                "axioms.py: the ledger of conditional laws is stale.\n"
                "Run `python3 tools/jlt-lint/axioms.py --write` and commit the result,\n"
                "so that the change is in the diff for review."
            )
        held = LEDGER.read_text(encoding="utf-8").splitlines() if LEDGER.exists() else []
        if held != current:
            sys.stdout.writelines(
                difflib.unified_diff(
                    [l + "\n" for l in held],
                    [l + "\n" for l in current],
                    "tools/jlt-lint/axioms.txt (checked in)",
                    "the sources",
                )
            )
            sys.exit(
                "axioms.py: the ledger is stale: an axiom was added, removed or changed.\n"
                "Run `python3 tools/jlt-lint/axioms.py --write` and commit the result,\n"
                "so that the change is in the diff for review."
            )
        print(f"axioms.py: the ledger holds, {len(current) - len(HEADER)} axioms")
        return
    print("\n".join(current))


if __name__ == "__main__":
    main(sys.argv[1:])
